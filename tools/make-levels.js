// Builds data/levels.js: how high each T20 competition scores, season by
// season (the average completed first innings), so the win model knows what
// a good total is in the BBL, the Women's Premier League or a T20I; and how
// much easier or harder chasing is there than the model expects (its edge,
// fitted as tools/accuracy.js --edge tests it).
//   node tools/make-levels.js <folder> [<folder> ...]
// Folders of Cricsheet JSON files, e.g. the unzipped ipl_json.zip, bbl_json.zip
// and t20s_json.zip from https://cricsheet.org/downloads/. Run it again after
// each season.
const fs = require('fs');
const path = require('path');
const E = require('../engine.js');
const Cs = require('../adapters/cricsheet.js');

const dirs = process.argv.slice(2);
if (!dirs.length) { console.error('usage: node tools/make-levels.js <cricsheet folder> [...]'); process.exit(1); }

const sums = {};
const chases = {}; // completed chases by competition, for the edge
for (const dir of dirs) {
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json'))) {
    const cs = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    const i = cs.info;
    const o = i.outcome || {};
    // A first innings that ran its course: no rain rule, no abandonment.
    if (i.match_type !== 'T20' || i.overs !== 20 || o.method || o.result === 'no result') continue;
    const reg = cs.innings.filter((x) => !x.super_over && x.overs);
    if (reg.length < 2) continue;
    const c = Cs.competitionOf(cs);
    const total = reg[0].overs.reduce((a, ov) => a + ov.deliveries.reduce((x, d) => x + d.runs.total, 0), 0);
    const s = ((sums[c.key] = sums[c.key] || {})[c.season] = sums[c.key][c.season] || { n: 0, t: 0 });
    s.n++; s.t += total;
    if (o.winner) (chases[c.key] = chases[c.key] || []).push({ season: c.season, target: total + 1, won: o.winner === reg[1].team ? 1 : 0, states: statesOf(reg[1]) });
  }
}

// Score, wickets and balls before each ball of an innings.
function statesOf(inn) {
  const out = [];
  let r = 0;
  let w = 0;
  let legal = 0;
  for (const ov of inn.overs) {
    let inOver = 0;
    for (const d of ov.deliveries) {
      out.push({ r, w, legal });
      r += d.runs.total;
      w += (d.wickets || []).filter((x) => !/retired hurt|retired not out/.test(x.kind)).length;
      if (!(d.extras && (d.extras.wides || d.extras.noballs))) inOver++;
      legal = ov.over * 6 + Math.min(6, inOver);
    }
  }
  return out;
}
// The shift in log-odds that best fits these chases, each match counting
// once, pulled towards none so a handful of matches cannot swing it.
function fitEdge(rows, prior = 0.4) {
  const sig = (x) => 1 / (1 + Math.exp(-x));
  let d = 0;
  for (let it = 0; it < 20; it++) {
    let g = -d / (prior * prior);
    let h = 1 / (prior * prior);
    for (const s of rows) {
      const p = sig(Math.log(s.p / (1 - s.p)) + d);
      g += s.w * (s.y - p);
      h += s.w * p * (1 - p);
    }
    d += g / h;
  }
  return d;
}

const competitions = {};
const latest = { male: [], female: [] };
for (const [key, seasons] of Object.entries(sums).sort()) {
  // Seasons with too few matches say little; leave them out.
  const kept = Object.entries(seasons).filter(([, s]) => s.n >= 8);
  if (!kept.length) continue;
  competitions[key] = Object.fromEntries(kept.map(([season, s]) => [season, Math.round(s.t / s.n)]));
  const [name, gender] = key.split('|');
  const [, last] = kept[kept.length - 1];
  if (name !== 'T20I associates') latest[gender].push(Math.round(last.t / last.n));
}
const median = (a) => { const s = a.slice().sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : null; };
// For a competition not in the table: the middle of the latest levels.
const defaults = { male: median(latest.male), female: median(latest.female) };

// Each competition's chasing edge, scoring every chase with the level a live
// app would have had (the season before; the first season, its own).
const edges = {};
for (const [key, list] of Object.entries(chases)) {
  const by = competitions[key];
  if (!by) continue;
  const seasons = Object.keys(by).map(Number);
  const rows = [];
  for (const m of list) {
    const prev = seasons.filter((s) => s < m.season).pop();
    const L = by[prev != null ? prev : seasons.find((s) => s >= m.season)];
    if (!L) continue;
    const st = m.states.filter((x) => x.w < 10 && x.legal < 120 && x.r < m.target);
    for (const x of st) rows.push({ y: m.won, w: 1 / st.length, p: Math.min(1 - 1e-6, Math.max(1e-6, E.chaseWinChance(2, x.r, x.w, x.legal, m.target, L))) });
  }
  edges[key] = +fitEdge(rows).toFixed(2);
}
const levels = { defaults, competitions, edges };

const out = path.join(__dirname, '..', 'data', 'levels.js');
fs.writeFileSync(out, `// Generated by tools/make-levels.js from Cricsheet match files (cricsheet.org,
// Open Data Commons Attribution License). Average completed first-innings
// total by competition and season, and each competition's chasing edge, for
// the win model. Do not edit by hand.
(function (root, levels) {
  if (typeof module === 'object' && module.exports) module.exports = levels;
  else root.DIPIN_LEVELS = levels;
})(typeof self !== 'undefined' ? self : globalThis, ${JSON.stringify(levels)});
`);
console.log(`${Object.keys(competitions).length} competitions -> data/levels.js (${(fs.statSync(out).size / 1024).toFixed(1)} KB); defaults: men ${defaults.male}, women ${defaults.female}`);
for (const [key, by] of Object.entries(competitions)) {
  const ss = Object.keys(by);
  console.log(`  ${key.padEnd(40)} ${ss[0]}-${ss[ss.length - 1]}  latest ${by[ss[ss.length - 1]]}  chasing edge ${edges[key] >= 0 ? '+' : ''}${edges[key]}`);
}
