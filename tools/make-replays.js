// Packs the Cricsheet match files in data/cricsheet into data/replays.js, so
// the page (and the single-file build) can offer them without fetching.
// Usage: node tools/make-replays.js
const fs = require('fs');
const path = require('path');

// Per-match settings: what to call it, and what Cricsheet cannot tell us.
const MATCHES = {
  // scoring: IPL 2019 average first-innings total, from Cricsheet (tools/calibrate.js prints it)
  1181768: { label: 'IPL 2019 Final: MI v CSK', event: 'IPL 2019 Final', start: 19 * 60 + 30, scoring: 168 },
  // No scoring given: the app looks it up in data/levels.js (T20Is between full members).
  1415755: { label: 'T20 World Cup 2024 Final: IND v SA', event: "Men's T20 World Cup 2024 Final", start: 10 * 60 + 30 },
};

const dir = path.join(__dirname, '..', 'data', 'cricsheet');
const replays = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => {
  const id = path.basename(f, '.json');
  const cricsheet = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const opts = Object.assign({ id }, MATCHES[id] || {});
  const label = opts.label || `${cricsheet.info.teams.join(' v ')}, ${cricsheet.info.dates[0]}`;
  delete opts.label;
  return { id, label, options: opts, cricsheet };
});
const out = path.join(__dirname, '..', 'data', 'replays.js');
fs.writeFileSync(out, `// Generated by tools/make-replays.js from Cricsheet match files (cricsheet.org,\n// Open Data Commons Attribution License). Do not edit by hand.\nwindow.DIPIN_REPLAYS = ${JSON.stringify(replays)};\n`);
console.log(`${replays.length} replay(s) -> data/replays.js (${(fs.statSync(out).size / 1024).toFixed(1)} KB)`);

